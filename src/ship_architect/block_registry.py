"""Exact 1.21.1 block/state/name validation. Never substitutes a different block.
Vanilla data is generated by the official Mojang server; mod data is per document.
"""
from functools import lru_cache
import json,re
from pathlib import Path

class MaterialError(ValueError):pass

@lru_cache(maxsize=1)
def vanilla():
    return json.loads((Path(__file__).parent/'data/vanilla_1_21_1.json').read_text(encoding='utf-8'))['blocks']

def norm(value):return re.sub(r'[\s_\-]','',value).casefold()

@lru_cache(maxsize=1)
def aliases():
    result={}
    for key,row in vanilla().items():
        for name in (key,key.split(':')[1],row['ko']):result.setdefault(norm(name),set()).add(key)
    for name,key in {'석재블록':'minecraft:stone','석재블럭':'minecraft:stone','돌블록':'minecraft:stone','돌블럭':'minecraft:stone','석재':'minecraft:stone','참나무목재블록':'minecraft:oak_planks','유리블록':'minecraft:glass','돌벽돌':'minecraft:stone_bricks','오크판자':'minecraft:oak_planks','참나무목재':'minecraft:oak_planks','참나무원목':'minecraft:oak_log'}.items():result.setdefault(norm(name),set()).add(key)
    return result

STATE=re.compile(r'([a-z0-9_.-]+:[a-z0-9_./-]+)(?:\[([^\[\]]+)\])?\Z')

def split_state(value):
    match=STATE.fullmatch(value)
    if not match:raise MaterialError('블록 ID/상태 형식 오류: '+value)
    props={}
    if match[2]:
        for pair in match[2].split(','):
            bits=pair.split('=')
            if len(bits)!=2 or not all(re.fullmatch(r'[a-z0-9_.-]+',s) for s in bits) or bits[0] in props:raise MaterialError('블록 상태 형식/중복 오류: '+value)
            props[bits[0]]=bits[1]
    return match[1],props


def state_name(base,properties):return base+('['+','.join(k+'='+v for k,v in sorted(properties.items()))+']' if properties else '')


def validate_mod_registry(data):
    if type(data) is not dict or data.get('minecraft_version')!='1.21.1' or type(data.get('blocks')) is not dict:raise MaterialError('모드 목록은 minecraft_version=1.21.1, blocks 객체가 필요합니다.')
    if len(data['blocks'])>4096 or len(json.dumps(data).encode())>2_000_000:raise MaterialError('모드 목록 크기 제한 초과')
    output={}
    for base,row in data['blocks'].items():
        b,p=split_state(base)
        if b.startswith('minecraft:') or p or type(row) is not dict:raise MaterialError('모드 ID/목록 형식 오류: '+base)
        props=row.get('properties',{});default=row.get('default',{})
        if type(props) is not dict or type(default) is not dict or len(props)>32 or set(default)!=set(props):raise MaterialError('모드 기본 상태/속성 오류: '+base)
        for k,values in props.items():
            if not re.fullmatch(r'[a-z0-9_.-]+',k) or type(values) is not list or not values or len(values)>128 or any(type(v) is not str or not re.fullmatch(r'[a-z0-9_.-]+',v) for v in values) or default[k] not in values:raise MaterialError('모드 속성 값 오류: '+base)
        # Explicitly attested plain decoration only. Registry presence alone is not safety.
        safe=row.get('safe_full_cube') is True and row.get('has_block_entity') is False and row.get('functional') is False
        if any(word in base.split(':')[0] for word in ('computercraft','cc_tweaked')):safe=False
        output[base]={'properties':props,'default':default,'safe_full_cube':safe,'has_block_entity':row.get('has_block_entity',True),'functional':row.get('functional',True)}
    return output


class BlockRegistry:
    def __init__(self,palette=(),mods=None):
        self.observed=list(palette.values()) if isinstance(palette,dict) else list(palette)
        self.mods=mods or {}

    def resolve(self,value):
        if type(value) is not str or not value.strip() or len(value)>1024:raise MaterialError('블록 이름/ID를 입력하세요.')
        value=value.strip()
        if ':' not in value:
            suffix=''
            if '[' in value:
                value,suffix=value.split('[',1);suffix='['+suffix
            choices=aliases().get(norm(value),set())
            if len(choices)!=1:raise MaterialError('알 수 없거나 모호한 블록 이름: '+value+' · 블록 목록에서 정확한 ID를 선택하세요.')
            value=next(iter(choices))+suffix
        base,props=split_state(value)
        row=vanilla().get(base) if base.startswith('minecraft:') else self.mods.get(base)
        if row is None:
            if value in self.observed:return value  # observed exact state; no invented properties
            raise MaterialError('사용 가능함을 확인할 수 없는 블록/상태: '+value+' · 기존 팔레트 또는 모드 레지스트리가 필요합니다.')
        if any(k not in row['properties'] or v not in row['properties'][k] for k,v in props.items()):raise MaterialError('존재하지 않는 블록 상태: '+value)
        props={**row['default'],**props}
        for old in self.observed:
            try:b,p=split_state(old)
            except MaterialError:continue
            if b==base and {**row['default'],**p}==props:return old
        return state_name(base,props)

    def safe_mod(self,state):
        base,_=split_state(state);return bool(self.mods.get(base,{}).get('safe_full_cube'))

    def provenance(self,state):
        base,_=split_state(state)
        if base in vanilla():return '공식 Java 1.21.1 목록/상태 검증'
        if base in self.mods:return '사용자가 불러온 모드 목록/상태 검증 (실행 중 게임 조회 아님)'
        return '기존 schem의 정확한 상태 관측 (현재 모드 설치 여부는 미확인)'


def prompt_mentions(prompt,registry):
    """Exact IDs and official Korean labels; longest matches win. No fuzzy guesses."""
    found=[]
    for m in re.finditer(r'[a-z0-9_.-]+:[a-z0-9_./-]+(?:\[[^\]\n]+\])?',prompt):found.append((m.start(),m.end(),registry.resolve(m[0])))
    explicit=list(found)
    for m in re.finditer(r'(?<![a-z0-9_:])[a-z]+(?:_[a-z0-9]+)+(?:\[[^\]\n]+\])?',prompt):
        if norm(m[0].split('[')[0]) in aliases() and not any(m.start()<b and m.end()>a for a,b,_ in explicit):found.append((m.start(),m.end(),registry.resolve(m[0])))
    normalized=[];positions=[]
    for i,c in enumerate(prompt):
        if not re.fullmatch(r'[\s_\-]',c):normalized.append(c.casefold());positions.append(i)
    text=''.join(normalized)
    for alias,keys in aliases().items():
        if len(keys)!=1 or ':' in alias or (not re.search('[가-힣]',alias) and len(alias)<3):continue
        start=0
        while (at:=text.find(alias,start))>=0:
            end=at+len(alias);start=end
            if len(alias)==1 and text[end:end+1] not in ('로','으','을','를','만','블','바','벽','천','기','',','):continue
            lo=positions[at];hi=positions[end-1]+1
            if not re.search('[가-힣]',alias) and ((lo>0 and re.match(r'[A-Za-z0-9_]',prompt[lo-1])) or (hi<len(prompt) and re.match(r'[A-Za-z0-9_]',prompt[hi]))):continue
            if not any(lo<b and hi>a for a,b,_ in explicit):found.append((lo,hi,registry.resolve(next(iter(keys)))))
    # Remove short Korean labels contained in a longer recognized block label.
    found=sorted(found,key=lambda x:-(x[1]-x[0]));result=[]
    for item in found:
        if not any(item[0]<b and item[1]>a for a,b,_ in result):result.append(item)
    return sorted(result)


ROLES={'바닥':'floor','벽면':'walls','벽':'walls','천장':'ceiling','기둥':'column'}

def request_bindings(prompt,registry,overrides=None):
    mentions=prompt_mentions(prompt,registry)
    # Explicit material-shaped phrases must resolve, even if no known alias was
    # found. This prevents an unknown Korean material from becoming an example stone.
    hints=list(re.finditer(r'(?:바닥|벽면|벽|천장|기둥)\s*(?:재료)?\s*(?:은|는|:|=)\s*([^,;\n]+)',prompt))
    for hint in hints:
        lo,hi=hint.span(1);text=hint[1].strip()
        if any(lo<b and hi>a for a,b,_ in mentions):continue
        if re.match(r'(?:유지|그대로|삭제|없애|없이|만들지|[0-9]|Y|선택|전체|높이|두께)',text):continue
        candidate=re.split(r'(?:으로|로)\s|(?:으로|로)(?=만들|설계|채워|지어|깔아)|\s*(?:만들어|만들고|설계해|해주세요|해줘|해 줘)',text)[0].strip()
        if candidate:registry.resolve(candidate)
    for hint in re.finditer(r'([가-힣A-Za-z0-9_:]+?)(?:으로|로)\s*(?:바닥|벽|천장|기둥|만들|건축|설계|채워|지어|깔아)',prompt):
        if hint[1] in ('랜덤블록','랜덤블럭','여러블록','여러블럭','다른블록','다른블럭','임의블록','임의블럭'):continue
        if hint[1].endswith(('새','대','자동','적','순서','방식','방법')):continue
        if not any(hint.start(1)<b and hint.end(1)>a for a,b,_ in mentions):registry.resolve(hint[1])
    # Explicitly protected references are not requested construction materials.
    mentions=[m for m in mentions if not re.match(r'\s*(?:은|는|을|를)?\s*(?:보호|유지|제외|건드리지)',prompt[m[1]:])]
    if re.search(r'교체|바꾸',prompt):
        destinations=[m for m in mentions if re.match(r'\s*(?:으로|로)',prompt[m[1]:])]
        if destinations:mentions=[m for m in mentions if not (re.match(r'\s*(?:을|를|에서)',prompt[m[1]:]) and any(d[0]>m[1] for d in destinations))]
    bindings={}
    roles=list(re.finditer('바닥|벽면|벽|천장|기둥',prompt))
    for role in roles:
        # Commas delimit role/material assignments. A conjunction after a role
        # cannot steal the next role's material ("흰색 바닥과 유리 천장").
        left=max(prompt.rfind(c,0,role.start()) for c in (',',';','\n'))+1
        right=min([v for c in (',',';','\n') if (v:=prompt.find(c,role.end()))>=0] or [len(prompt)])
        candidates=[m for m in mentions if left<=m[0] and m[1]<=right]
        if re.match(r'\s*(?:과|와|및|하고)',prompt[role.end():]):candidates=[m for m in candidates if m[1]<=role.start()]
        elif re.match(r'\s*(?:은|는|을|를|에|:|=)',prompt[role.end():]):
            forward=[m for m in candidates if m[0]>=role.end() and not any(role.end()<=r.start()<m[0] for r in roles)]
            if forward:candidates=forward
        candidates=[m for m in candidates if not re.search(r'바꾸|교체|유지|삭제|만들|추가|설계|생성|채우|건축',prompt[m[1]:role.start()] if m[1]<=role.start() else prompt[role.end():m[0]] if m[0]>=role.end() else '')]
        if candidates:
            closest=min(candidates,key=lambda m:min(abs(m[1]-role.start()),abs(m[0]-role.end())))
            if min(abs(closest[1]-role.start()),abs(closest[0]-role.end()))<=40:bindings[ROLES[role[0]]]=closest[2]
    for key,value in (overrides or {}).items():
        if key not in ('floor','walls','ceiling','column'):raise MaterialError('지원하지 않는 재료 역할: '+key)
        if value.strip():bindings[key]=registry.resolve(value)
    return bindings,sorted({m[2] for m in mentions}|set(bindings.values()))


@lru_cache(maxsize=4096)
def valid_vanilla_state(state):
    if not state.startswith('minecraft:'):return False
    try:BlockRegistry().resolve(state);return True
    except MaterialError:return False
